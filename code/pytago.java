public class pytago {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        int t = sc.nextInt();

        while (t-- > 0) {
            int n = sc.nextInt();

            long[] a = new long[n];

            for (int i = 0; i < n; i++) {
                long x = sc.nextLong();
                a[i] = x * x;
            }

            Arrays.sort(a);

            boolean ok = false;

            // Chọn c^2
            for (int i = n - 1; i >= 2; i--) {
                int left = 0;
                int right = i - 1;

                while (left < right) {
                    long sum = a[left] + a[right];

                    if (sum == a[i]) {
                        ok = true;
                        break;
                    }

                    if (sum < a[i]) {
                        left++;
                    } else {
                        right--;
                    }
                }

                if (ok)
                    break;
            }

            System.out.println(ok ? "YES" : "NO");
        }

        sc.close();
    }
}